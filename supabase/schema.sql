create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, first_name, last_name, username, image, role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'first_name', split_part(coalesce(new.email, ''), '@', 1)),
    coalesce(new.raw_user_meta_data->>'last_name', ''),
    coalesce(new.raw_user_meta_data->>'username', split_part(coalesce(new.email, ''), '@', 1)),
    coalesce(new.raw_user_meta_data->>'avatar_url', new.raw_user_meta_data->>'picture', ''),
    'user'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.profiles enable row level security;
alter table public.addresses enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.contact_messages enable row level security;

create policy "public read categories" on public.categories for select using (true);
create policy "public read active products" on public.products
  for select using (is_active = true or public.is_admin());

create policy "read own profile" on public.profiles
  for select using (id = auth.uid());
create policy "admins read profiles" on public.profiles
  for select using (public.is_admin());
create policy "update own profile" on public.profiles
  for update using (id = auth.uid()) with check (id = auth.uid());

create policy "admins insert products" on public.products
  for insert with check (public.is_admin());
create policy "admins update products" on public.products
  for update using (public.is_admin()) with check (public.is_admin());
create policy "admins delete products" on public.products
  for delete using (public.is_admin());

create policy "admins insert categories" on public.categories
  for insert with check (public.is_admin());
create policy "admins update categories" on public.categories
  for update using (public.is_admin()) with check (public.is_admin());
create policy "admins delete categories" on public.categories
  for delete using (public.is_admin());

create policy "own addresses select" on public.addresses
  for select using (user_id = auth.uid());
create policy "own addresses insert" on public.addresses
  for insert with check (user_id = auth.uid());
create policy "own addresses delete" on public.addresses
  for delete using (user_id = auth.uid());

create policy "own orders select" on public.orders
  for select using (
    user_id = auth.uid()
    or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
  );
create policy "own orders insert" on public.orders
  for insert with check (user_id = auth.uid());
create policy "admins update orders" on public.orders
  for update using (public.is_admin()) with check (public.is_admin());

create policy "own order items select" on public.order_items
  for select using (
    exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid())
    or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
  );
create policy "own order items insert" on public.order_items
  for insert with check (
    exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid())
  );

create policy "anyone can contact" on public.contact_messages
  for insert with check (true);

create index if not exists products_brand_idx on public.products (brand);
create index if not exists orders_user_idx on public.orders (user_id);
create index if not exists addresses_user_idx on public.addresses (user_id);
