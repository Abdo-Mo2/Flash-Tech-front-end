-- Flash Tech catalog + auth-adjacent tables
-- Run this in the Supabase SQL editor, then run seed.sql.

create table if not exists public.categories (
  slug text primary key,
  name text not null,
  blurb text,
  icon text,
  sort_order int not null default 0
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  description text not null default '',
  price numeric(12,2) not null check (price >= 0),
  category text not null,
  brand text,
  stock integer not null default 0 check (stock >= 0),
  images jsonb not null default '[]'::jsonb,
  specifications jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_category_idx on public.products (category);
create index if not exists products_active_idx on public.products (is_active);
create index if not exists products_name_idx on public.products (name);

create or replace function public.set_products_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_updated_at on public.products;
create trigger products_updated_at before update on public.products
for each row execute function public.set_products_updated_at();

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  first_name text,
  last_name text,
  username text,
  phone text,
  gender text,
  image text,
  address text,
  role text not null default 'user' check (role in ('user', 'admin')),
  updated_at timestamptz not null default now()
);

create table if not exists public.addresses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  label text,
  full_name text,
  phone text,
  line1 text,
  city text,
  governorate text,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  status text not null default 'Processing',
  total numeric not null,
  placed_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint,
  title text not null,
  qty int not null,
  unit_price numeric not null,
  line_total numeric not null
);

create table if not exists public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  email text not null,
  topic text,
  message text not null,
  created_at timestamptz not null default now()
);

create or replace function public.create_order_with_items(p_total numeric, p_items jsonb)
returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  created_order_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  insert into public.orders (user_id, status, total)
  values (auth.uid(), 'Processing', p_total)
  returning id into created_order_id;

  insert into public.order_items (order_id, product_id, title, qty, unit_price, line_total)
  select created_order_id, item.product_id, item.title, item.qty, item.unit_price, item.line_total
  from jsonb_to_recordset(p_items) as item(
    product_id bigint,
    title text,
    qty int,
    unit_price numeric,
    line_total numeric
  );

  return created_order_id;
end;
$$;

